import { ArrowsClockwise, Database, Lightning } from "@phosphor-icons/react";
import type { ReactNode } from "react";
import type { ChatMetadata } from "../api/types";

interface MetaStripProps {
  metadata: ChatMetadata;
  simulated?: string;
  trailing?: ReactNode;
}

function Sep() {
  return (
    <span aria-hidden className="text-ink-300">
      /
    </span>
  );
}

/**
 * The path a request took through the key pool: failed keys struck through, then the key
 * that answered. The pool is always walked from key_1, so attempts fully describes it.
 */
function KeyRoute({ keyId, attempts }: { keyId: string | null; attempts: number }) {
  if (!keyId) {
    return <span title="No key used: served from cache">no key</span>;
  }
  const failed = Array.from({ length: attempts }, (_, i) => `key_${i + 1}`);
  return (
    <span className="inline-flex items-center gap-1.5" title="Route through the key pool">
      {failed.map((id) => (
        <span key={id} className="inline-flex items-center gap-1.5">
          <span className="text-coral-700/80 line-through decoration-coral-400/70">{id}</span>
          <span aria-hidden className="text-ink-400">
            &rarr;
          </span>
        </span>
      ))}
      <span className={attempts > 0 ? "text-signal-700" : ""}>{keyId}</span>
    </span>
  );
}

/**
 * Per-reply gateway metadata on a single mono line. Each data-testid element holds only
 * its raw contract value; labels and icons live outside it.
 */
export function MetaStrip({ metadata, simulated, trailing }: MetaStripProps) {
  const isCache = metadata.resolution_source === "LLM_CACHE";
  const attempts = metadata.fallback_attempts;

  return (
    <div
      className="flex flex-wrap items-center gap-x-2.5 gap-y-1.5 font-mono text-[11.5px] text-ink-500"
      aria-label="Response metadata"
    >
      <span
        className={`inline-flex items-center gap-1.5 rounded-md px-1.5 py-0.5 text-[11px] font-medium ${
          isCache
            ? "bg-ink-900 text-ink-100"
            : "bg-signal-100 text-signal-700 ring-1 ring-inset ring-signal-500/20"
        }`}
        title={isCache ? "Served from the LiteLLM response cache" : "Generated by a live model call"}
      >
        {isCache ? <Database size={12} weight="bold" /> : <Lightning size={12} weight="fill" />}
        <span data-testid="meta-source">{metadata.resolution_source}</span>
      </span>

      <span title="Model that produced the reply" className="text-ink-600">
        <span data-testid="meta-model">{metadata.model}</span>
      </span>
      <Sep />
      <span title="Server-measured latency for this request">
        <span data-testid="meta-latency" className="text-ink-700">
          {metadata.latency_ms} ms
        </span>
      </span>
      <Sep />
      <span title="Input tokens for this request (system + history + message)">
        in <span data-testid="meta-input-tokens" className="text-ink-700">{metadata.input_tokens}</span>
      </span>
      <span title="Output tokens for this reply">
        out{" "}
        <span data-testid="meta-output-tokens" className="text-ink-700">
          {metadata.output_tokens}
        </span>
      </span>
      <Sep />
      <KeyRoute keyId={metadata.key_id} attempts={attempts} />

      {attempts > 0 && (
        <span
          className="inline-flex items-center gap-1 rounded-md bg-flare-100 px-1.5 py-0.5 text-flare-700 ring-1 ring-inset ring-flare-500/20"
          title="Keys that failed before one succeeded"
        >
          <ArrowsClockwise size={11} weight="bold" />
          {attempts} {attempts === 1 ? "fallback" : "fallbacks"}
        </span>
      )}
      {simulated && (
        <span className="text-ink-500" title="X-Simulate-Failure header sent with this request">
          sim {simulated}
        </span>
      )}
      {trailing && <span className="ml-auto">{trailing}</span>}
    </div>
  );
}
