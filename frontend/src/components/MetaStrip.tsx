import { ArrowsClockwise, Cpu, Database, Key, Lightning, Timer } from "@phosphor-icons/react";
import type { ChatMetadata } from "../api/types";

interface MetaStripProps {
  metadata: ChatMetadata;
  simulated?: string;
}

/**
 * Per-reply gateway metadata. Each data-testid element contains only its raw value
 * (labels and icons live outside it), so the contract values can be read verbatim.
 */
export function MetaStrip({ metadata, simulated }: MetaStripProps) {
  const isCache = metadata.resolution_source === "LLM_CACHE";
  const attempts = metadata.fallback_attempts;

  return (
    <div className="flex flex-wrap items-center gap-1.5" aria-label="Response metadata">
      <span
        className={`chip ${
          isCache
            ? "bg-cache/[0.08] text-cache ring-cache/25"
            : "bg-live/[0.08] text-live ring-live/25"
        }`}
        title={isCache ? "Served from the LiteLLM response cache" : "Generated by a live model call"}
      >
        {isCache ? <Database size={12} weight="light" /> : <Lightning size={12} weight="light" />}
        <span data-testid="meta-source">{metadata.resolution_source}</span>
      </span>

      <span className="chip" title="Model that produced the reply">
        <Cpu size={12} weight="light" />
        <span data-testid="meta-model">{metadata.model}</span>
      </span>

      <span className="chip" title="Server-measured latency for this request">
        <Timer size={12} weight="light" />
        <span data-testid="meta-latency">{metadata.latency_ms} ms</span>
      </span>

      <span className="chip" title="Input tokens for this request (system + history + message)">
        <span className="text-white/35">in</span>
        <span data-testid="meta-input-tokens">{metadata.input_tokens}</span>
      </span>

      <span className="chip" title="Output tokens for this reply">
        <span className="text-white/35">out</span>
        <span data-testid="meta-output-tokens">{metadata.output_tokens}</span>
      </span>

      <span
        className="chip"
        title={metadata.key_id ? "API key that answered" : "No key used: served from cache"}
      >
        <Key size={12} weight="light" />
        {metadata.key_id ?? "none"}
      </span>

      {attempts > 0 && (
        <span
          className="chip bg-warn/[0.08] text-warn ring-warn/25"
          title="Keys that failed before one succeeded"
        >
          <ArrowsClockwise size={12} weight="light" />
          {attempts} {attempts === 1 ? "fallback" : "fallbacks"}
        </span>
      )}

      {simulated && (
        <span className="chip text-white/40" title="X-Simulate-Failure header sent with this request">
          simulated {simulated}
        </span>
      )}
    </div>
  );
}
